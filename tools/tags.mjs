import { NodeIO, getBounds } from '@gltf-transform/core';
const doc = await new NodeIO().read('field-raw.glb');
const scene = doc.getRoot().listScenes()[0];
const tags = {};
const walk = (n, id) => { const m = /AprilTag, ID (\d+)/.exec(n.getName()); if (m) id = +m[1];
  if (id != null && n.getMesh()) { const b = getBounds(n); const kind = /Vinyl/.test(n.getName()) ? 'v' : /Base Poly/.test(n.getName()) ? 'b' : 'o'; (tags[id] ??= {})[kind] = b; }
  for (const c of n.listChildren()) walk(c, id); };
for (const n of scene.listChildren()) walk(n, null);
for (const [id, t] of Object.entries(tags)) { const c = (b) => b && b.min.map((v, i) => ((v + b.max[i]) / 2).toFixed(4)).join(','); const sz = (b) => b && b.min.map((v, i) => (b.max[i] - v).toFixed(3)).join(','); console.log(id, 'v', c(t.v), sz(t.v), 'b', c(t.b), sz(t.b), t.o ? 'o' : ''); }
import fs from 'fs';
const src = fs.readFileSync(process.argv[2], 'utf8');
const codes = [...src.matchAll(/0x([0-9a-f]+)UL/g)].map((m) => m[1]);
const bx = [...src.matchAll(/bit_x\[(\d+)\] = (\d+);/g)].map((m) => +m[2]);
const by = [...src.matchAll(/bit_y\[(\d+)\] = (\d+);/g)].map((m) => +m[2]);
const out = [];
for (const [id, t] of Object.entries(tags)) {
  const c = (b) => b.min.map((v, i) => (v + b.max[i]) / 2);
  const v = c(t.v), b = c(t.b);
  // the sim turns the CAD 180 degrees about Y
  const p = [-v[0], v[1], -v[2]];
  const thinX = t.v.max[0] - t.v.min[0] < t.v.max[2] - t.v.min[2];
  // which way it faces: out of the HUB / TRENCH mount it's on (both centered on |x| = 3.645),
  // or into the field for tags on the end walls
  let n;
  if (Math.abs(p[0]) > 7) n = [-Math.sign(p[0]), 0, 0];
  else if (thinX) n = [Math.sign(p[0] - Math.sign(p[0]) * 3.645), 0, 0];
  else n = [0, 0, Math.sign(p[2])];
  out.push({ id: +id, p: p.map((x) => +x.toFixed(4)), n, code: codes[id] });
}
fs.writeFileSync(process.argv[3], `// AprilTags on the REBUILT field (tag36h11), positions from the official field CAD (sim frame).
// Generated by tools/fieldopt tags step; codes from AprilRobotics/apriltag (BSD-2).
export const TAG_BITS = { x: ${JSON.stringify(bx)}, y: ${JSON.stringify(by)} };
export const TAGS = ${JSON.stringify(out)};
`);
